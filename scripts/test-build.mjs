// Function to handle --update flag for golden snapshots
function updateSnapshots() {
  mkdirSync(SNAPSHOTS_DIR, { recursive: true });

  // 1. Build fixture site into dev/preview to capture full-build fixture-temple-b.html
  execFileSync(
    process.execPath,
    [join(ROOT, "scripts", "build.mjs"), "--data", "dev/fixtures", "--out", "dev/preview"],
    { cwd: ROOT, stdio: "pipe" }
  );

  const builtTempleB = readFileSync(join(ROOT, "dev", "preview", "temples", "fixture-temple-b.html"), "utf8");
  writeFileSync(join(SNAPSHOTS_DIR, "fixture-temple-b.html"), builtTempleB, "utf8");

  // 2. Snapshot of full journey temple exercising all 12 classes
  const fullHtml = renderFullJourneyTemple("dev/fixtures");
  writeFileSync(join(SNAPSHOTS_DIR, "temple-journey-full.html"), fullHtml, "utf8");

  console.log(`Updated snapshots in ${relative(ROOT, SNAPSHOTS_DIR).replace(/\\/g, "/")}:`);
  console.log(`  - fixture-temple-b.html`);
  console.log(`  - temple-journey-full.html`);
}

// If invoked with --update, update snapshots and exit cleanly
if (process.argv.includes("--update")) {
  updateSnapshots();
  process.exit(0);
}

