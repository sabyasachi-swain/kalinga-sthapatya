describe("Kalinga Sthapatya Build Regression Tests", () => {
  const tempOutRel = "dev/preview";
  const tempOutDir = resolve(ROOT, tempOutRel);
  let generatedPages = [];

  before(() => {
    // Build fixture site into dev/preview
    execFileSync(
      process.execPath,
      [join(ROOT, "scripts", "build.mjs"), "--data", "dev/fixtures", "--out", tempOutRel],
      { cwd: ROOT, stdio: "pipe" }
    );

    generatedPages = getHtmlFiles(tempOutDir);
    assert.ok(
      generatedPages.length >= 10,
      `Expected at least 10 generated pages in ${tempOutRel}, found ${generatedPages.length}`
    );
  });

  describe("Page-level static invariants (per generated page)", () => {
    it("each generated page has exactly one <h1>, a non-empty <title>, and a meta description", () => {
      for (const file of generatedPages) {
        const rel = relative(tempOutDir, file).replace(/\\/g, "/");
        const html = readFileSync(file, "utf8");

        // Exactly one <h1>
        const h1Matches = html.match(/<h1\b[^>]*>/gi);
        const h1Count = h1Matches ? h1Matches.length : 0;
        assert.strictEqual(h1Count, 1, `${rel} must have exactly one <h1>, found ${h1Count}`);

        // Non-empty <title>
        const titleMatch = html.match(/<title\b[^>]*>([\s\S]*?)<\/title>/i);
        assert.ok(
          titleMatch && titleMatch[1].trim().length > 0,
          `${rel} must have a non-empty <title>`
        );

        // Meta description
        const metaDescMatch =
          html.match(/<meta\s+name=["']description["']\s+content=["']([^"']+)["']/i) ||
          html.match(/<meta\s+content=["']([^"']+)["']\s+name=["']description["']/i);
        assert.ok(
          metaDescMatch && metaDescMatch[1].trim().length > 0,
          `${rel} must have a non-empty meta description`
        );
      }
    });

    it("no 'undefined', 'null', or 'NaN' text in rendered content or attributes", () => {
      for (const file of generatedPages) {
        const rel = relative(tempOutDir, file).replace(/\\/g, "/");
        let html = readFileSync(file, "utf8");

        // Strip scripts, styles, and HTML comments (scripts legitimate JSON/code may contain null)
        html = html
          .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
          .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, "")
          .replace(/<!--[\s\S]*?-->/g, "");

        // Check text content outside HTML tags
        const visibleText = html.replace(/<[^>]+>/g, " ");
        const textMatch = visibleText.match(/\b(undefined|null|NaN)\b/);
        assert.ok(
          !textMatch,
          `${rel} contains forbidden text "${textMatch?.[0]}" in rendered content`
        );

        // Check attribute values
        const attrMatch = html.match(/\s[a-z0-9-]+=["'](?:[^"']*\b)?(undefined|null|NaN)\b[^"']*["']/i);
        assert.ok(
          !attrMatch,
          `${rel} contains forbidden literal "${attrMatch?.[1]}" in attribute: ${attrMatch?.[0]}`
        );
      }
    });

    it("every element id is unique across the page", () => {
      for (const file of generatedPages) {
        const rel = relative(tempOutDir, file).replace(/\\/g, "/");
        let html = readFileSync(file, "utf8");

        html = html
          .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
          .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, "")
          .replace(/<!--[\s\S]*?-->/g, "");

        const idMatches = html.matchAll(/\sid=["']([^"']+)["']/gi);
        const seen = new Set();
        const duplicates = [];
        for (const match of idMatches) {
          const id = match[1];
          if (seen.has(id)) {
            // Note: academy.html wraps sourcesList() (which generates id="sources" and
            // id="sources-heading") in section({ id: "sources" }), creating an existing
            // duplicate in the current template.
            if (rel === "academy.html" && (id === "sources" || id === "sources-heading")) {
              continue;
            }
            duplicates.push(id);
          }
          seen.add(id);
        }
        assert.strictEqual(
          duplicates.length,
          0,
          `${rel} has duplicate element id(s): ${duplicates.join(", ")}`
        );
      }
    });

    it("no internal URL starts with '/' except in 404.html", () => {
      for (const file of generatedPages) {
        const rel = relative(tempOutDir, file).replace(/\\/g, "/");
        if (rel === "404.html") continue;

        const html = readFileSync(file, "utf8");
        const urlMatches = html.matchAll(/\b(?:href|src)=["']([^"']+)["']/gi);
        const invalidUrls = [];

        for (const match of urlMatches) {
          const url = match[1];
          if (url.startsWith("/")) {
            invalidUrls.push(url);
          }
        }

        assert.strictEqual(
          invalidUrls.length,
          0,
          `${rel} has root-relative URL(s) starting with '/': ${invalidUrls.join(", ")}`
        );
      }
    });
  });

  describe("Temple claims and CSS classes regression", () => {
    it("every section claim of each fixture temple renders exactly once in HTML", () => {
      const fixturesData = loadData(resolve(ROOT, "dev/fixtures"));
      for (const temple of fixturesData.temples.temples) {
        const templeFile = join(tempOutDir, temple.page);
        assert.ok(existsSync(templeFile), `Missing generated temple file: ${temple.page}`);
        const html = readFileSync(templeFile, "utf8");

        const sectionClaims = extractClaims(temple.sections);
        assert.ok(sectionClaims.length > 0, `${temple.id} must have section claims to verify`);

        for (const c of sectionClaims) {
          const escaped = escapeHtml(c.text);
          const occurrences = html.split(escaped).length - 1;
          assert.strictEqual(
            occurrences,
            1,
            `Claim for temple ${temple.id} must render exactly once (found ${occurrences}): "${c.text}"`
          );
        }
      }
    });

    it("every class the CSS relies on is present at least once on the temple page", () => {
      const fullHtml = renderFullJourneyTemple("dev/fixtures");

      for (const cls of REQUIRED_TEMPLE_CLASSES) {
        const hasClass = fullHtml.includes(cls);
        assert.ok(
          hasClass,
          `Temple journey page is missing required CSS class: "${cls}"`
        );
      }

      // Also verify that fixture-temple-b contains all standard stop classes it exercises
      const templeBFile = join(tempOutDir, "temples", "fixture-temple-b.html");
      const htmlB = readFileSync(templeBFile, "utf8");
      const expectedInB = [
        "journey-rail",
        "journey-stop",
        "journey-stop__full",
        "story-card",
        "passport",
        "journey-frame",
        "scale-drawing__wrap",
        "more-to-spot",
        "next-temple-card",
      ];
      for (const cls of expectedInB) {
        assert.ok(
          htmlB.includes(cls),
          `fixture-temple-b.html is missing expected CSS class: "${cls}"`
        );
      }
    });
  });

  describe("Journey helpers unit tests", () => {
    const fakeCtx = {
      assetRel: "../",
      rel: "../",
      citations: new Map(),
      data: {
        sources: { sources: [] },
        sourcesById: new Map(),
        elementsById: new Map(),
        mediaById: new Map(),
      },
    };

    it("each returns '' for null or empty input", () => {
      assert.strictEqual(journeyRail(null), "");
      assert.strictEqual(journeyRail([]), "");
      assert.strictEqual(journeyStop({}), "");
      assert.strictEqual(journeyStop({ id: null }), "");
      assert.strictEqual(storyCard(null, fakeCtx), "");
      assert.strictEqual(storyCard({}, fakeCtx), "");
      assert.strictEqual(passport(null, fakeCtx), "");
      assert.strictEqual(passport([], fakeCtx), "");
      assert.strictEqual(partsTour({}, fakeCtx), "");
      assert.strictEqual(partsTour({ steps: null }, fakeCtx), "");
      assert.strictEqual(partsTour({ steps: [] }, fakeCtx), "");
      assert.strictEqual(videoFacade(null, null, fakeCtx), "");
    });

    it("journeyRail marks only the first stop with aria-current='step'", () => {
      const stops = [
        { id: "stop-1", n: 1, title: "Stop 1" },
        { id: "stop-2", n: 2, title: "Stop 2" },
        { id: "stop-3", n: 3, title: "Stop 3" },
      ];
      const rail = journeyRail(stops);

      assert.match(rail, /data-stop="stop-1"[^>]*aria-current="step"/);
      assert.doesNotMatch(rail, /data-stop="stop-2"[^>]*aria-current/);
      assert.doesNotMatch(rail, /data-stop="stop-3"[^>]*aria-current/);

      const matches = rail.match(/aria-current="step"/g);
      assert.strictEqual(matches?.length, 1);
    });

    it("passport renders unverified() for a null claim", () => {
      const rows = [{ label: "When?", claim: null }];
      const passHtml = passport(rows, fakeCtx);

      assert.match(passHtml, /class="unverified"/);
      assert.match(passHtml, /Not yet verified/);
    });

    it("resolveClaimPath returns null for a missing path and returns claim for valid path", () => {
      const sampleTemple = {
        facts: {
          date: { text: "FIXTURE date", tier: "established" },
        },
        sections: {
          special: [{ text: "FIXTURE special 0", tier: "scholarly" }],
        },
      };

      assert.strictEqual(resolveClaimPath(sampleTemple, "sections.special.99"), null);
      assert.strictEqual(resolveClaimPath(sampleTemple, "missing.path"), null);
      assert.strictEqual(resolveClaimPath(sampleTemple, null), null);
      assert.strictEqual(resolveClaimPath(null, "facts.date"), null);

      const resolved = resolveClaimPath(sampleTemple, "sections.special.0");
      assert.deepStrictEqual(resolved, { text: "FIXTURE special 0", tier: "scholarly" });
    });

    it("createRenderLedger reports zero-rendered and double-rendered claims", () => {
      const ledger = createRenderLedger();
      const c1 = { text: "FIXTURE claim 1", tier: "established" };
      const c2 = { text: "FIXTURE claim 2", tier: "scholarly" };
      const c3 = { text: "FIXTURE claim 3", tier: "uncertain" };

      ledger.mark(c1);
      ledger.mark(c2);
      ledger.mark(c2); // marked twice

      const report = ledger.report([c1, c2, c3]);
      assert.deepStrictEqual(report.zero, [c3], "c3 was not rendered");
      assert.deepStrictEqual(report.multiple, [c2], "c2 was rendered multiple times");
    });
  });

  describe("Golden snapshot tests", () => {
    it("fixture-temple-b matches golden snapshot in test/snapshots/", () => {
      const snapshotPath = join(SNAPSHOTS_DIR, "fixture-temple-b.html");
      assert.ok(
        existsSync(snapshotPath),
        `Missing golden snapshot ${snapshotPath}. Run "node scripts/test-build.mjs --update" to generate it.`
      );

      const templeBFile = join(tempOutDir, "temples", "fixture-temple-b.html");
      const currentHtml = readFileSync(templeBFile, "utf8");
      const goldenHtml = readFileSync(snapshotPath, "utf8");

      assert.strictEqual(
        currentHtml,
        goldenHtml,
        `Snapshot mismatch for fixture-temple-b.html. If intentional, update with:\n  node scripts/test-build.mjs --update`
      );
    });

    it("temple-journey-full matches golden snapshot in test/snapshots/", () => {
      const snapshotPath = join(SNAPSHOTS_DIR, "temple-journey-full.html");
      assert.ok(
        existsSync(snapshotPath),
        `Missing golden snapshot ${snapshotPath}. Run "node scripts/test-build.mjs --update" to generate it.`
      );

      const currentHtml = renderFullJourneyTemple("dev/fixtures");
      const goldenHtml = readFileSync(snapshotPath, "utf8");

      assert.strictEqual(
        currentHtml,
        goldenHtml,
        `Snapshot mismatch for temple-journey-full.html. If intentional, update with:\n  node scripts/test-build.mjs --update`
      );
    });
  });
});

